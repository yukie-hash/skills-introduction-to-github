#include "libft.h"

void	ft_bzero(void *s, size_t n)
{
	size_t				i;
	unsigned char		*u_s;

	u_s = (unsigned char *)s;
	i = 0;
	while (i < n)
	{
		u_s[i] = '\0';
		i++;
	}
}
